"""Regenerate txspeakers.json: Japanese speaker name -> USA English speaker name (Episode III).

The translation editor's "By speaker" view groups dialogue by the name in
the ``[Speaker]`` prefix of each line. A project on the Japanese discs (or
the Japanese original shown next to the English) carries the Japanese name,
so the view needs to know which English name the same speaker has. This
takes every scene script whose text pool has the same number of strings on
both builds (paired index for index, ``align.speaker_map``), counts the
(Japanese speaker, USA speaker) pairs, and keeps, for each Japanese name, the
English name paired with it most often. Nothing is typed in.

    python3 txspeakers.py --usa USA_DISC.iso --jp JP_DISC.iso [--out txspeakers.json]

Either disc of each set may be given (``txdiscs.pair`` finds the other).
"""
from __future__ import annotations

import argparse
import json
import unicodedata
from pathlib import Path

ABOUT = ("Speaker names for the translation editor's 'By speaker' view. Each Japanese [Speaker] prefix "
         "(Xenosaga Episode III Japan, SLPS_256.40/41) is paired with the USA discs' [Speaker] of the "
         "same string in the scene scripts whose pools have the same number of strings on both builds; "
         "the English shown is the USA name paired with it most often. Generated by txspeakers.py from "
         "the discs, not written by hand. Keys are NFKC-normalised, U+2212 as '-'.")


def norm(name: str) -> str:
    return unicodedata.normalize("NFKC", name).replace("−", "-")


def build(usa: str, jp: str) -> dict:
    import align as alignmod
    import textcodec
    import textpack
    import txdiscs
    import txfam_core as core
    import txsource
    us_st = core.load_set(txdiscs.pair(usa))
    jp_st = core.load_set(txdiscs.pair(jp))
    ju, jj = txsource._by_common(us_st), txsource._by_common(jp_st)
    kind = textpack.KINDS["sb"]
    pools = []
    for name, ou in ju.items():
        oj = jj.get(name)
        if ou.kind != "sb" or oj is None:
            continue
        a = kind.items(oj.path, oj.data, jp_st.region)
        b = kind.items(ou.path, ou.data, us_st.region)
        if len(a) == len(b):
            pools.append((a, b))
    smap = alignmod.speaker_map(pools)
    cj, cu = textcodec.codec_by_name(jp_st.region.codec), textcodec.codec_by_name(us_st.region.codec)
    out = {}
    for k, v in smap.items():
        j, e = norm(cj.to_text(k)), cu.to_text(v)
        if j and e and "⟦" not in j and "⟦" not in e:
            out[j] = e
    return {"_about": ABOUT, "ja_to_en": dict(sorted(out.items()))}


def load() -> dict:
    """The shipped table (empty if the file is missing)."""
    try:
        return json.loads((Path(__file__).with_name("txspeakers.json")).read_text("utf-8"))["ja_to_en"]
    except (OSError, ValueError, KeyError):
        return {}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--usa", required=True)
    ap.add_argument("--jp", required=True)
    ap.add_argument("--out", default=str(Path(__file__).with_name("txspeakers.json")))
    a = ap.parse_args()
    data = build(a.usa, a.jp)
    Path(a.out).write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", "utf-8")
    print(f"{len(data['ja_to_en'])} Japanese names -> {a.out}")


if __name__ == "__main__":
    main()
